import com.synapticloop.h2zero.base.exception.H2ZeroFinderException;
import com.synapticloop.h2zero.base.exception.H2ZeroPrimaryKeyException;
import com.synapticloop.h2zero.base.validator.bean.ValidationBean;
import org.json.JSONObject;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.sql.Connection;
import java.sql.SQLException;

/**
 * <p>This is the base class for all h2zero generated models and defines the
 * required functionality for a working model.  It contains methods to insert,
 * update and delete itself.</p>
 *
 * <p>ModelBase provides abstract methods that must be implemented by concrete
 * model classes generated by h2zero, as well as convenience methods for common
 * database operations like insert, update, upsert, delete, ensure, and refresh,
 * with both transactional (requiring a Connection) and auto-closing (managing
 * its own Connection) variants, including silent versions that log exceptions.</p>
 */
public abstract class ModelBase extends ConstantModelBase {
	private static final Logger LOGGER = LoggerFactory.getLogger(ModelBase.class);

	/**
	 * A flag indicating whether the model has changes to any of its fields or values.
	 * This is typically used to determine if an update operation is necessary.
	 */
	protected boolean isDirty = false;

	/**
	 * <p>Abstract method to determine whether the primary key is set for this model instance.</p>
	 *
	 * @return true if the primary key is set, false otherwise.
	 */
	public abstract boolean primaryKeySet();

	/**
	 * <p>Abstract method to validate the current state of the model for operations
	 * such as insertion or update.</p>
	 *
	 * @return a {@link ValidationBean} indicating the validity of the model.
	 */
	public abstract ValidationBean validate();

	/**
	 * <p>Abstract method to retrieve a database connection from the appropriate
	 * connection manager. Subclasses are responsible for implementing how connections
	 * are obtained.</p>
	 *
	 * @return A {@link Connection} to the database.
	 *
	 * @throws SQLException If there was an error with retrieving the connection.
	 */
	protected abstract Connection getConnection() throws SQLException;

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the insert methods
	 *
	 * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Abstract method to persist the model object to the database using a provided connection.</p>
	 *
	 * <p>The caller is responsible for managing (opening and closing) the provided connection.</p>
	 *
	 * @param connection the SQL connection to be used - this connection __MUST__
	 *                   be closed by the caller.
	 *
	 * @throws SQLException if there was an error in the SQL expression.
	 * @throws H2ZeroPrimaryKeyException if the model already has a primary key
	 *    set, indicating it might be an update operation instead of an insert.
	 */
	public abstract void insert(Connection connection) throws SQLException, H2ZeroPrimaryKeyException;

	/**
	 * <p>Persist the model object to the database by automatically managing a connection.</p>
	 *
	 * <p>In effect this is a chained call to the <code>insert(Connection connection)</code>
	 * method, creating a new connection, executing the call, and then closing the
	 * connection</p>
	 *
	 * @throws SQLException if there was an error in the SQL expression.
	 * @throws H2ZeroPrimaryKeyException if the model already has a primary key
	 *  set, indicating it might be an update operation instead of an insert.
	 */
	public void insert() throws SQLException, H2ZeroPrimaryKeyException {
		try (Connection connection = getConnection()) {
			insert(connection);
		}
	}

	/**
	 * <p>Persist the model object to the database silently, swallowing any SQL or
	 * H2Zero exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 */
	public void insertSilent() {
		try (Connection connection = getConnection()){
			insert(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error("Could not insert", ex);
		}
	}

	/**
	 * <p>Persist the model object to the database silently using a provided connection,
	 * swallowing any SQL or H2Zero exceptions that occur.</p>
	 *
	 * <p>The caller is responsible for managing the provided connection. Exceptions are logged as errors.</p>
	 *
	 * @param connection the SQL connection to be used.
	 */
	public void insertSilent(Connection connection) {
		try {
			insert(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error("Could not insert", ex);
		}
	}

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the update methods
	 *
	 * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Abstract method to update the model object in the database using a provided connection.</p>
	 *
	 * <p>The caller is responsible for managing (opening and closing) the provided connection.</p>
	 *
	 * @param connection The connection to the database.
	 *
	 * @throws SQLException if there was an error with the SQL expression.
	 * @throws H2ZeroPrimaryKeyException if the primary key is not set for this
	 *     model, indicating an update cannot be performed.
	 */
	public abstract void update(Connection connection) throws SQLException, H2ZeroPrimaryKeyException;

	/**
	 * <p>Update the model utilising the passed in connection, the caller must
	 * close the connection.  If there are any exceptions thrown from subsequent
	 * calls, these will be caught, swallowed, and logged</p>.
	 *
	 * <p>The caller is responsible for managing the provided connection. Exceptions are logged as errors.</p>
	 *
	 * @param connection The connection to the database.
	 */
	public void updateSilent(Connection connection) {
		try {
			update(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Update the model object in the database by automatically managing a connection.</p>
	 *
	 * <p>This method obtains a connection, performs the update operation, and then
	 * closes the connection automatically.</p>
	 *
	 * @throws SQLException If there was an error with the updating of the model.
	 * @throws H2ZeroPrimaryKeyException If the primary key is not set for this
	 *                                   model, indicating an update cannot be performed.
	 */
	public void update() throws SQLException, H2ZeroPrimaryKeyException {
		try (Connection connection = getConnection()) {
			update(connection);
		}
	}

	/**
	 * <p>Update the model object in the database silently, swallowing any SQL or
	 * H2Zero exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 */
	public void updateSilent() {
		try (Connection connection = getConnection()) {
			update(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the upsert methods
	 *
	 * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Performs an "upsert" operation on the model object using a provided connection.</p>
	 *
	 * <p>An insert is performed if the primary key is not set; otherwise, an update is performed.</p>
	 * <p>The caller is responsible for managing the provided connection.</p>
	 *
	 * @param connection The connection to use for transactional purposes.
	 * @throws H2ZeroPrimaryKeyException if the return value for the primary key
	 *                                   could not be determined or if an update is attempted without a primary key.
	 * @throws SQLException if there was an error with the SQL statement.
	 */
	public void upsert(Connection connection) throws H2ZeroPrimaryKeyException, SQLException {
		if(!primaryKeySet()) {
			insert(connection);
		} else {
			update(connection);
		}
	}

	/**
	 * <p>Performs an "upsert" operation on the model object by automatically managing a connection.</p>
	 *
	 * <p>An insert is performed if the primary key is not set; otherwise, an update is performed.
	 * This method obtains a connection, performs the upsert operation, and then closes the connection automatically.</p>
	 *
	 * @throws H2ZeroPrimaryKeyException if the return value for the primary key
	 *                                   could not be determined or if an update is attempted without a primary key.
	 * @throws SQLException if there was an error with the SQL statement.
	 */
	public void upsert() throws H2ZeroPrimaryKeyException, SQLException {
		try (Connection connection = getConnection()){
			upsert(connection);
		}
	}

	/**
	 * <p>Performs an "upsert" operation on the model object silently using a provided connection,
	 * swallowing any exceptions that occur.</p>
	 *
	 * <p>An insert is performed if the primary key is not set; otherwise, an update is performed.
	 * The caller is responsible for managing the provided connection. Exceptions are logged as errors.</p>
	 *
	 * @param connection The connection to use for transactional purposes.
	 */
	public void upsertSilent(Connection connection) {
		try {
			upsert(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Performs an "upsert" operation on the model object silently, swallowing any
	 * exceptions that occur.</p>
	 *
	 * <p>An insert is performed if the primary key is not set; otherwise, an update is performed.
	 * This method obtains a connection, performs the upsert operation, and then closes the connection automatically.
	 * Exceptions are logged as errors.</p>
	 */
	public void upsertSilent() {
		try {
			upsert();
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the delete methods
	 *
	 * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Abstract method to delete this model instance from the database using its primary key
	 * and a provided connection.</p>
	 *
	 * <p>The caller is responsible for managing (opening and closing) the provided connection.</p>
	 *
	 * @param connection The connection to use - note that this connection __MUST__
	 *                   be closed by the caller.
	 * @throws SQLException If there was an error with the SQL statement.
	 * @throws H2ZeroPrimaryKeyException If the primary key is null, indicating
	 *                                   the model cannot be deleted.
	 */
	public abstract void delete(Connection connection) throws SQLException, H2ZeroPrimaryKeyException;

	/**
	 * <p>Delete this model instance from the database silently using a provided connection,
	 * swallowing any exceptions that occur.</p>
	 *
	 * <p>The caller is responsible for managing the provided connection. Exceptions are logged as errors.</p>
	 *
	 * @param connection The connection to use - note that this connection __MUST__
	 *                   be closed by the caller.
	 */
	public void deleteSilent(Connection connection) {
		try {
			delete(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Delete this model instance from the database by automatically managing a connection.</p>
	 *
	 * <p>This method obtains a connection, performs the delete operation, and then
	 * closes the connection automatically.</p>
	 *
	 * @throws SQLException If there was an error with the SQL statement.
	 * @throws H2ZeroPrimaryKeyException If the primary key is null, indicating
	 *                                   the model cannot be deleted.
	 */
	public void delete() throws SQLException, H2ZeroPrimaryKeyException {
		try (Connection connection = getConnection()) {
			delete(connection);
		}
	}

	/**
	 * <p>Delete the model object from the database silently, swallowing any exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 */
	public void deleteSilent() {
		try (Connection connection = getConnection()) {
			delete(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the hydrate methods
	 *
	 * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Hydrate any fields that are not automatically populated. By default, this
	 * does nothing unless over-written in the child classes.</p>
	 *
	 * @param connection The connection to use.
	 *
	 * @throws SQLException If there was an error in the SQL statement.
	 * @throws H2ZeroPrimaryKeyException If the primary key is null.
	 */
	protected void hydrate(Connection connection) throws SQLException, H2ZeroPrimaryKeyException {
		// do nothing
	}

	/**
	 * <p>Hydrate any fields that are not automatically populated silently using a provided connection,
	 * swallowing any exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 *
	 * @param connection The connection to use.
	 */
	protected void hydrateSilent(Connection connection) {
		try {
			hydrate(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Hydrate any fields that are not automatically populated by automatically managing a connection.</p>
	 *
	 * <p>This method obtains a connection, performs the hydrate operation, and then
	 * closes the connection automatically.</p>
	 *
	 * @throws SQLException If there was an error in the SQL statement.
	 * @throws H2ZeroPrimaryKeyException If the primary key is null.
	 */
	protected void hydrate() throws SQLException, H2ZeroPrimaryKeyException {
		try (Connection connection = getConnection()) {
			hydrate(connection);
		}
	}

	/**
	 * <p>Hydrate any fields that are not automatically populated silently, swallowing any
	 * exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 */
	protected void hydrateSilent() {
		try (Connection connection = getConnection()) {
			hydrate(connection);
		} catch(H2ZeroPrimaryKeyException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/* * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
	 *
	 * All the refresh methods
	 *
   * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * */

	/**
	 * <p>Abstract method to refresh the model instance with the latest data from the database
	 * using its primary key and a provided connection.</p>
	 *
	 * <p>The caller is responsible for managing the provided connection.</p>
	 *
	 * @param connection The connection to use.
	 *
	 * @throws SQLException If there was an error in the SQL statement.
	 * @throws H2ZeroPrimaryKeyException If the primary key is null.
	 * @throws H2ZeroFinderException If the model could not be found in the database.
	 */
	public abstract void refresh(Connection connection) throws SQLException, H2ZeroPrimaryKeyException, H2ZeroFinderException;

	/**
	 * <p>Refresh the model instance with the latest data from the database by automatically
	 * managing a connection.</p>
	 *
	 * <p>This method obtains a connection, performs the refresh operation, and then
	 * closes the connection automatically.</p>
	 *
	 * @throws SQLException if there was an error in the SQL statement.
	 * @throws H2ZeroPrimaryKeyException if the primary key is null.
	 * @throws H2ZeroFinderException If the model could not be found in the database.
	 */
	public void refresh() throws SQLException, H2ZeroPrimaryKeyException, H2ZeroFinderException {
		try (Connection connection = getConnection()) {
			refresh(connection);
		}
	}

	/**
	 * <p>Refresh the model instance silently, swallowing any exceptions that occur.</p>
	 *
	 * <p>Exceptions are logged as errors.</p>
	 */
	public void refreshSilent() {
		try {
			refresh();
		} catch(H2ZeroPrimaryKeyException | H2ZeroFinderException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Refresh the model instance silently using a provided connection, swallowing any
	 * exceptions that occur.</p>
	 *
	 * <p>The caller is responsible for managing the provided connection. Exceptions are logged as errors.</p>
	 *
	 * @param connection The connection to use.
	 */
	public void refreshSilent(Connection connection) {
		try {
			refresh(connection);
		} catch(H2ZeroPrimaryKeyException | H2ZeroFinderException | SQLException ex) {
			LOGGER.error(ex.getMessage(), ex);
		}
	}

	/**
	 * <p>Determines whether two objects differ. This is a utility method for comparing
	 * current and new values of fields to detect changes.</p>
	 *
	 * @param from the first object to be checked against.
	 * @param to the second object to be checked.
	 *
	 * @return true if the objects differ (or one is null and the other isn't), false otherwise.
	 */
	protected boolean isDifferent(Object from, Object to) {
		if(null == from) {
			return(to != null);
		} else {
			if(null == to) {
				return(true);
			} else {
				return(!from.equals(to));
			}
		}
	}

	/**
	 * <p>Adds a key-value pair to a {@link JSONObject}. This is a convenience method.</p>
	 *
	 * @param jsonObject The JSONObject to add the key-value pair to.
	 * @param key The key for the new entry.
	 * @param object The value for the new entry.
	 */
	protected void addToJSONObject(JSONObject jsonObject, String key, Object object) {
		jsonObject.put(key, object);
	}

	/**
	 * <p>Returns the JSON representation of the model. This is a convenience method
	 * that delegates to {@link #toJSON()}.</p>
	 *
	 * @return A {@link JSONObject} representing the model's current state.
	 */
	public JSONObject getToJSON() {
		return(toJSON());
	}

	/**
	 * <p>Abstract method to convert the model's current state into a {@link JSONObject}.</p>
	 *
	 * @return A {@link JSONObject} representing the model.
	 */
	public abstract JSONObject toJSON();

	/**
	 * <p>Abstract method to convert the model's current state into a JSON formatted string.</p>
	 *
	 * @return A JSON formatted string representing the model.
	 */
	public abstract String toJsonString();

	/**
	 * <p>Abstract method to retrieve the JSON formatted string representation of the model.
	 * This is a convenience method that delegates to {@link #toJsonString()}.</p>
	 *
	 * @return A JSON formatted string representing the model.
	 */
	public abstract String getJsonString();
}
